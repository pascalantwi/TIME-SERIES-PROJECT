"""Build the online figure/table pages that the report links to.

Reads the figures and tables (with their captions and numbers) from appendix.tex,
typesets each one as its own captioned page, and writes
  ../linked_results/Figure_NN.png, Table_NN.png   (opened by the links in the report)
  ../linked_results/Supplement_Figures_and_Tables.pdf  (all items in one PDF)
  links.tex   (\\lnk{label} -> clickable "Figure n" / "Table n" pointing online)

Run from the report folder after make_appendix_tables.py:  python3 make_linked_results.py
"""
import pathlib
import re
import shutil
import subprocess

BASE_URL = ("https://raw.githubusercontent.com/pascalantwi/time-series-project/main/"
            "TIME%20SERIES%20REPORT/CO2%20Project/linked_results/")
HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "linked_results"
BUILD = HERE / "_build_linked"
OUT.mkdir(exist_ok=True)
BUILD.mkdir(exist_ok=True)

PREAMBLE = r"""\documentclass[border=18pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage[sc]{mathpazo}
\usepackage{amsmath, amssymb, graphicx, booktabs, adjustbox, xcolor}
\definecolor{accent}{HTML}{1C5CAB}
\graphicspath{{%(fig)s/}}
\newcommand{\co}{CO$_2$}
\newcommand{\ppm}{\,ppm}
\begin{document}
\begin{minipage}{6.5in}
"""


def braced(text, start):
    """Return the contents of the {...} group that opens at text[start]."""
    assert text[start] == "{"
    depth = 0
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start + 1:i], i + 1
    raise ValueError("unbalanced braces")


src = (HERE / "appendix.tex").read_text(encoding="utf-8")
items = []
for m in re.finditer(r"\\begin\{figure\}.*?\\end\{figure\}", src, re.S):
    block = m.group(0)
    graphic = re.search(r"\\includegraphics\[[^\]]*\]\{([^}]*)\}", block).group(1)
    cap, _ = braced(block, block.index(r"\caption{") + len(r"\caption"))
    label = re.search(r"\\label\{([^}]*)\}", block).group(1)
    items.append(("Figure", m.start(), graphic, cap, label))
for m in re.finditer(r"^\\apptable", src, re.M):
    pos = m.end()
    args = []
    for _ in range(3):
        arg, pos = braced(src, pos)
        args.append(arg)
    items.append(("Table", m.start(), args[0], args[1], args[2]))
items.sort(key=lambda t: t[1])

links = [r"% Generated by make_linked_results.py: each label opens its figure/table online.",
         r"\newcommand{\lnk}[1]{\csname lnk@#1\endcsname}"]
pdfs = []
count = {"Figure": 0, "Table": 0}
for kind, _, file, cap, label in items:
    count[kind] += 1
    n = count[kind]
    name = f"{kind}_{n:02d}"
    if kind == "Figure":
        body = (rf"\centering\includegraphics[width=\linewidth]{{{file}}}\par\vspace{{8pt}}"
                rf"\raggedright{{\small\textbf{{\color{{accent}}Figure {n}.}} {cap}}}")
    else:
        body = (rf"\raggedright{{\small\textbf{{\color{{accent}}Table {n}.}} {cap}}}\par\vspace{{8pt}}"
                rf"\centering\small\begin{{adjustbox}}{{max width=\linewidth}}\input{{{HERE / 'tables' / file}}}\end{{adjustbox}}")
    tex = PREAMBLE % {"fig": (HERE.parent / "figures").as_posix()} + body + "\n\\end{minipage}\n\\end{document}\n"
    (BUILD / f"{name}.tex").write_text(tex, encoding="utf-8")
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"{name}.tex"],
                   cwd=BUILD, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["pdftoppm", "-r", "250", "-png", "-singlefile", f"{name}.pdf", str(OUT / name)],
                   cwd=BUILD, check=True)
    pdfs.append(str(BUILD / f"{name}.pdf"))
    url = BASE_URL + f"{name}.png"
    links.append(rf"\expandafter\def\csname lnk@{label}\endcsname{{\href{{{url.replace('%', chr(92) + '%')}}}{{{kind}~{n}}}}}")
    print(f"{name}: {label}")

subprocess.run(["pdfunite", *pdfs, str(OUT / "Supplement_Figures_and_Tables.pdf")], check=True)
(HERE / "links.tex").write_text("\n".join(links) + "\n", encoding="utf-8")
shutil.rmtree(BUILD)
print(f"{count['Figure']} figures, {count['Table']} tables -> {OUT}")
